package oracle_test

import (
	"context"
	"testing"

	"github.com/jackc/pgx/v5"

	"github.com/Leo-Zh9/stutter/internal/oracle"
	"github.com/Leo-Zh9/stutter/internal/testenv"
)

// The "generated" rule read from a real catalog: volatile and stable
// defaults, identity and serial columns are generated; constants are not.
func TestCatalogGeneratedRule(t *testing.T) {
	env := testenv.Env(t)
	ctx := context.Background()
	if err := env.CreateTemplate(ctx, "tpl_test_catalog", `
		CREATE TABLE p (
			id     text PRIMARY KEY DEFAULT 'p_' || gen_random_uuid()::text,
			n      bigint GENERATED ALWAYS AS IDENTITY,
			s      serial,
			at     timestamptz DEFAULT now(),
			label  text DEFAULT 'fixed',
			qty    int DEFAULT 1 + 2,
			due    timestamp(3) without time zone,
			due_tz timestamptz(6)
		);
		CREATE TABLE c (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, p_id text REFERENCES p(id), note text);
		INSERT INTO p DEFAULT VALUES;
		INSERT INTO c (p_id, note) SELECT id, 'x' FROM p;
		CREATE SCHEMA billing;
		CREATE TABLE billing.inv (id text PRIMARY KEY DEFAULT 'in_' || gen_random_uuid()::text, p_id text REFERENCES p(id));
		INSERT INTO billing.inv (p_id) SELECT id FROM p;`); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { env.Drop(ctx, "tpl_test_catalog") })
	conn, err := pgx.Connect(ctx, env.DSN("tpl_test_catalog"))
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close(ctx)
	st, err := oracle.Snapshot(ctx, conn, []string{"public", "billing"})
	if err != nil {
		t.Fatal(err)
	}
	temporal := map[string]bool{}
	for _, tb := range st.Tables {
		for _, c := range tb.Columns {
			temporal[tb.Name+"."+c.Name] = c.Temporal
		}
	}
	for _, col := range []string{"p.at", "p.due", "p.due_tz"} {
		if !temporal[col] {
			t.Errorf("%s not recognised as a timestamp", col)
		}
	}
	if temporal["p.label"] {
		t.Error("text column treated as a timestamp")
	}
	gen := map[string]bool{}
	fk := map[string]string{}
	for _, tb := range st.Tables {
		for _, c := range tb.Columns {
			gen[tb.Name+"."+c.Name] = c.Generated
			if c.FKTable != "" {
				fk[tb.Name+"."+c.Name] = c.FKTable
			}
		}
	}
	want := map[string]bool{
		"p.id": true, "p.n": true, "p.s": true, "p.at": true, "p.label": false, "p.qty": false,
		"c.id": true, "c.p_id": false, "c.note": false,
	}
	for col, w := range want {
		if gen[col] != w {
			t.Errorf("%s: generated=%v, want %v", col, gen[col], w)
		}
	}
	if !gen["billing.inv.id"] || fk["billing.inv.p_id"] != "p" || len(st.Rows["billing.inv"]) != 1 {
		t.Errorf("non-public schema not read: gen=%v fk=%q rows=%d", gen["billing.inv.id"], fk["billing.inv.p_id"], len(st.Rows["billing.inv"]))
	}
	if fk["c.p_id"] != "p" {
		t.Errorf("c.p_id should be an edge to p, got %q", fk["c.p_id"])
	}
	if len(st.Rows["p"]) != 1 || len(st.Rows["c"]) != 1 {
		t.Fatalf("rows not read: %v", st.Rows)
	}
}
