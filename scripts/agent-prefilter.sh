#!/usr/bin/env bash
# Mechanical pre-filter for the agent blind hunt (docs/evidence/agent-protocol.md).
# Reads docs/evidence/agent-search.json in order and keeps each repository
# whose default branch, at its HEAD today, declares a PostgreSQL LangGraph
# checkpointer in a dependency file. Uses only the GitHub API: nothing is
# cloned or run. Writes docs/evidence/agent-prefilter.md.
set -euo pipefail
cd "$(dirname "$0")/.."
IN=docs/evidence/agent-search.json
OUT=docs/evidence/agent-prefilter.md
PY='langgraph-checkpoint-postgres'
JS='@langchain/langgraph-checkpoint-postgres'
DEPFILE='(^|/)(pyproject\.toml|requirements[^/]*\.txt|setup\.py|setup\.cfg|uv\.lock|poetry\.lock|Pipfile|package\.json)$'

{
  echo "# Agent hunt pre-filter"
  echo
  echo "Generated by \`scripts/agent-prefilter.sh\` on $(date -u +%Y-%m-%dT%H:%M:%SZ) from \`agent-search.json\`. A repository is kept when a dependency file at its default branch's HEAD names \`$PY\` or \`$JS\`. Kept repositories are judged in this order."
  echo
  echo "| Search rank | Repository | Stars | Pinned SHA | Matched |"
  echo "|---|---|---|---|---|"
} > "$OUT"

n=$(jq length "$IN")
kept=0
for ((i = 0; i < n; i++)); do
  repo=$(jq -r ".[$i].fullName" "$IN")
  stars=$(jq -r ".[$i].stargazersCount" "$IN")
  branch=$(jq -r ".[$i].defaultBranch" "$IN")
  sha=$(gh api "repos/$repo/commits/$branch" --jq .sha 2>/dev/null || true)
  [ -z "$sha" ] && { echo "rank $((i + 1)) $repo: unreadable, skipped" >&2; continue; }
  files=$(gh api "repos/$repo/git/trees/$sha?recursive=1" --jq '.tree[] | select(.type=="blob") | .path' 2>/dev/null | grep -E "$DEPFILE" | grep -v node_modules | head -40 || true)
  match=""
  while IFS= read -r f; do
    [ -z "$f" ] && continue
    body=$(gh api "repos/$repo/contents/$f?ref=$sha" -H "Accept: application/vnd.github.raw" 2>/dev/null || true)
    if grep -qF -- "$JS" <<<"$body"; then
      match="$f: $JS"; break
    fi
    if grep -qF -- "$PY" <<<"$body"; then
      match="$f: $PY"; break
    fi
  done <<<"$files"
  if [ -n "$match" ]; then
    kept=$((kept + 1))
    echo "| $((i + 1)) | $repo | $stars | \`$sha\` | \`$match\` |" >> "$OUT"
  fi
  echo "rank $((i + 1))/$n $repo: ${match:-no}" >&2
done
echo >> "$OUT"
echo "Kept $kept of $n." >> "$OUT"
