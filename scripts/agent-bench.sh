#!/usr/bin/env bash
# Hunts every miniagent variant with every single fault and writes
# results/agents.md. Each variant's full report is in
# targets/miniagent/hunt-<variant>/.
set -uo pipefail
cd "$(dirname "$0")/.."
CFG=targets/miniagent/stutter.json
VARIANTS=(correct approval-no-claim chat-no-dedupe claim-before-refund note-keyed-on-tool-call write-before-interrupt)
for v in "${VARIANTS[@]}"; do
  env=""
  [ "$v" != correct ] && env="BUG=$v"
  echo "== $v" >&2
  ./bin/stutter hunt -config "$CFG" -out "targets/miniagent/hunt-$v" -lanes "${LANES:-6}" ${env:+-env "$env"} >/dev/null
  code=$?
  [ $code -eq 2 ] && { echo "hunt failed for $v" >&2; exit 2; }
done
{
  echo "# miniagent results"
  echo
  echo "Generated by \`make agent-bench\` on $(date -u +%Y-%m-%dT%H:%M:%SZ). Each cell: single-fault schedules that changed the app's tables / schedules that fired deterministically (not fired, diverged, nondetermined in brackets)."
  echo
  echo "| Variant | lost | concurrent | crash | Findings | Repro in 10 replays |"
  echo "|---|---|---|---|---|---|"
  for v in "${VARIANTS[@]}"; do
    f="targets/miniagent/hunt-$v/results.json"
    cell() { jq -r --arg t "$1" '.by_fault_type[$t] // {} | "\(.failed // 0) / \(.n_fired // 0) (\(.n_not_fired // 0), \(.diverged // 0), \(.nondetermined // 0))"' "$f"; }
    echo "| $v | $(cell lost) | $(cell concurrent) | $(cell crash) | $(jq '.findings | length' "$f") | $(jq -r '[.findings[].reproduced_in_replays] | map(tostring) | join(", ")' "$f") |"
  done
} > results/agents.md
cat results/agents.md
